// Full warehouse: packed overflow survives a genuine engine sortie and failed placement.
const {assert,boot,clone,extract,stamp,v12,valid}=require('./game-fixture.cjs');
const seed=boot().g,s=clone(seed.s);
s.stash={bolt:192,water:1};
s.stashSlots=Array.from({length:192},(_,i)=>({uid:'s-overflow-fill-'+i,g:'bolt',x:i%6,y:Math.floor(i/6),w:1,h:1}));
let b=boot({[v12]:s}),g=b.g;
valid(g);
const money=g.s.wallet;
assert.equal(g.stock('water'),1);
assert.equal(g.s.stashSlots.some(u=>u.g==='water'),false);
g.gear({gear:'pack',id:'water',unit:'overflow'});
assert.equal(g.stock('water'),0);
assert.equal(g.s.equipment.bag.filter(u=>u.g==='water').length,1);
g.start();
assert.equal(g.s.field.bag.filter(u=>u.g==='water').length,1);
stamp(b,g.s.raid.startedAt+420000);
extract(b);
assert.equal(g.s.lastSummary.rating,'success');
assert.equal(g.stock('water'),1);
assert.equal(g.s.stashSlots.length,192);
assert.equal(g.s.stashSlots.some(u=>u.g==='water'),false);
g.ack();g.ack();
b=boot(new Map(b.storage),b.clock);g=b.g;
valid(g);
assert.equal(g.stock('water'),1);
assert.equal(g.s.stashSlots.length,192);
assert.equal(g.s.wallet,money);
const before=clone(g.s);
g.stashAction({stash:'select',id:'water',uid:'overflow'});
g.stashAction({stash:'auto'});
assert.deepEqual(clone(g.s),before);
for(const i of [0,6])g.sell('bolt','s-overflow-fill-'+i);
assert.equal(g.stock('bolt'),190);
assert.equal(g.stock('water'),1);
assert.equal(g.s.wallet,money+4500);
const unplaced=clone(g.s);
g.stashAction({stash:'select',id:'water',uid:'overflow'});
const set=b.storage.set;
b.storage.set=()=>{throw Error('quota')};
g.stashAction({stash:'auto'});
b.storage.set=set;
let current=clone(g.s);
assert.deepEqual(current,{...unplaced,revision:current.revision});
g.stashAction({stash:'select',id:'water',uid:'overflow'});
g.stashAction({stash:'auto'});
const placed=g.s.stashSlots.filter(u=>u.g==='water');
assert.equal(placed.length,1);
assert.deepEqual([placed[0].x,placed[0].y,placed[0].w,placed[0].h],[0,0,1,2]);
assert.equal(g.stock('water'),1);
assert.equal(g.s.wallet,money+4500);
valid(g);
const persisted=clone(g.s);
g=boot(new Map(b.storage),b.clock).g;
current=clone(g.s);
assert.deepEqual(current,{...persisted,revision:current.revision});
valid(g);
console.log('PASS full warehouse: real engine sortie, overflow recovery, duplicate ack, blocked placement, two exact sales, quota rollback, physical placement and reload.');
