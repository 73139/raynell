// The sale tray only holds references. Count physical originals once, wherever the player owns them.
const {assert,boot,clone,v12,valid}=require('./game-fixture.cjs');
const old=require('./fixtures/ward-market-v33.json').session;
const sheet='rl_bp_dressing',ids=['s-manual-a','s-manual-b','s-manual-c','s-manual-d','s-manual-e'];
const session=clone(old);
session.hideout.wardManual={registered:false,waiting:['s-manual-handoff']};
session.hideout.production={};
session.stash[sheet]=ids.length;
session.stashSlots=session.stashSlots.filter(u=>u.g!==sheet);
session.stashSlots.push(...ids.map((uid,x)=>({uid,g:sheet,x,y:0,w:1,h:1})));
const b0=boot({[v12]:session});
const [,w,h]=b0.g.goods.rs_case_docs;
const seed=clone(b0.g.s);
seed.stash.rs_case_docs=1;
seed.stashSlots.push({uid:'s-docs',g:'rs_case_docs',x:0,y:12,w,h});
const b=boot({[v12]:seed}),g=b.g;
valid(g);
g.gear({gear:'pack',id:sheet,unit:ids[3]});
assert.equal(g.s.equipment.bag.find(u=>u.g===sheet).uid,ids[3]);
assert.ok(g.caseMove('s-docs','put',sheet).ok);
assert.equal(g.s.stashSlots.find(u=>u.uid==='s-docs').contents[0].uid,ids[4]);
const loose=g.s.stashSlots.filter(u=>u.g===sheet).map(u=>u.uid);
assert.equal(loose.length,3);
const before=clone(g.s),wallet=g.fee;
const quote=g.saleQuote('quarter',loose);
assert.equal(quote.total,1800);
assert.match(g.wardSaleNote(3,'tray'),/판매대 원본 3장 판매 시 보유 원본 3장 남음/);
assert.match(g.wardSaleNote(1,'direct'),/보유 원본 5장 남음/);
assert.equal(g.wardSaleNote(0,'tray'),'');
assert.deepEqual(clone(g.s),before);
assert.ok(!g.saleQuote('medic',loose).ok);
assert.ok(!g.saleQuote('quarter',[loose[0],loose[0]]).ok);
const set=b.storage.set;b.storage.set=()=>{throw Error('quota');};
assert.ok(!g.saleCommit('quarter',loose,quote.token).ok);
b.storage.set=set;
assert.deepEqual(clone(g.s),before);
assert.ok(g.saleCommit('quarter',loose,quote.token).ok);
assert.ok(!g.saleCommit('quarter',loose,quote.token).ok);
assert.equal(g.fee,wallet+1800);
assert.deepEqual(clone(g.s.saleReceipts.quarter.lines),[{item:sheet,unit:600,uids:clone(loose)}]);
const reloaded=boot(b.storage,b.clock).g;
reloaded.build({id:'med',hideout:'manual-register',uid:'s-manual-handoff'});
assert.ok(reloaded.s.hideout.wardManual.registered);
assert.equal(reloaded.wardSaleNote(1,'tray'),'');
valid(reloaded);
const simple=clone(old);
delete simple.hideout.wardManual;simple.hideout.production={};simple.hideout.levels.med=0;
const fresh=boot({[v12]:simple}).g;
assert.match(fresh.wardSaleNote(1,'direct'),/마지막 보유 원본까지 판매/);
assert.match(fresh.wardSaleNote(1,'direct'),/의무실 Lv.1부터/);
const last=fresh.s.stashSlots.find(u=>u.g===sheet),balance=fresh.fee;
fresh.sell(sheet,last.uid);
assert.equal(fresh.fee,balance+600);
assert.equal(fresh.stock(sheet),0);
valid(fresh);
console.log('PASS three loose originals plus bag, document case, clinic handoff; old unregistered clinic, quote purity, rollback, exact UIDs/credit once, registration hides advice and last-copy sale remains allowed.');
