const {assert,boot,clone,go,valid,v12,setTestCash}=require('./game-fixture.cjs');
const NOTE='cr_notes';
const b=boot(),g=b.g;
const cash=()=>Array.from(g.searchOwned('CR 지폐')).filter(r=>r.id===NOTE);
const count=rows=>rows.reduce((s,r)=>s+r.quantity,0);
const sum=rows=>rows.reduce((s,r)=>s+r.cashAmount,0);
const capital=g.s.cash.pocket[0].uid;
assert.ok(g.cashAction(capital,'stash',4000,4,20).ok);
assert.ok(g.cashAction(capital,'bag',2000,1,1).ok);
assert.ok(g.cashAction(capital,'bag',3000,2,1).ok);
assert.equal(count(cash()),4);
assert.equal(sum(cash()),30000);
assert.equal(sum(cash().filter(r=>r.kind!=='bag')),25000);
assert.equal(sum(cash().filter(r=>r.kind==='bag')),5000);
const loose=cash().find(r=>r.kind==='stash');
assert.equal(loose.cashAmount,4000);
assert.deepEqual([loose.row,loose.col],[21,5]);
assert.equal(g.locateOwned(loose.key).uid,loose.uid);
const definition=clone(g.s);
definition.stash.rs_case_docs=1;
definition.stashSlots.push({uid:'s-search-docs',g:'rs_case_docs',alias:'CR 지폐 기록',w:1,h:2,x:0,y:0});
const seeded=boot({[v12]:definition});
const lookup=()=>Array.from(seeded.g.searchOwned('지폐'));
assert.equal(count(lookup().filter(r=>r.id!==NOTE)),1);
assert.equal(lookup().find(r=>r.id==='rs_case_docs').cashAmount,undefined);
assert.equal(lookup().filter(r=>r.id===NOTE).length,4);
const dormant=JSON.stringify(seeded.g.s);
seeded.click({page:'prep'});
assert.match(seeded.content(),/data-prep-cash><span>반입 지폐<\/span><b>5,000 CR/);
assert.equal(JSON.stringify(seeded.g.s),dormant);
seeded.g.start();
assert.equal(lookup().filter(r=>r.scope==='raid'&&r.kind==='bag').length,2);
assert.equal(sum(lookup().filter(r=>r.scope==='raid'&&r.kind==='bag')),5000);
const held=lookup().find(r=>r.scope==='raid');
go(seeded,'abandon');
assert.equal(seeded.g.locateOwned(held.key),null);
assert.equal(sum(lookup().filter(r=>r.id===NOTE)),25000);
valid(seeded.g);
const max=clone(boot().g.s);
setTestCash(max,Number.MAX_SAFE_INTEGER);
const high=boot({[v12]:max});
assert.equal(high.g.searchOwned('CR 지폐')[0].quantity,1);
assert.equal(high.g.searchOwned('CR 지폐')[0].cashAmount,Number.MAX_SAFE_INTEGER);
assert.ok(high.g.cashAction(high.g.s.cash.pocket[0].uid,'bag',17).ok);
assert.equal(high.g.fee,Number.MAX_SAFE_INTEGER-17);
valid(high.g);
console.log('PASS quantities count physical bundles; denominations remain exact across drawer, warehouse, preparation, live field, loss and max-safe amounts; normal bag and alias remain ordinary quantities.');
